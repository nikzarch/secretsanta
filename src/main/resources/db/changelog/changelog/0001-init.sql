CREATE TABLE users
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    TEXT        NOT NULL UNIQUE,
    telegram_id BIGINT      UNIQUE,
    password    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE secret_santa_events
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL,
    description TEXT,
    event_date  DATE        NOT NULL,
    owner_id    INTEGER     NOT NULL REFERENCES users (id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE event_participants
(
    event_id INTEGER NOT NULL REFERENCES secret_santa_events (id) ON DELETE CASCADE,
    user_id  INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, user_id)
);

CREATE TABLE santa_assignments
(
    event_id    INTEGER NOT NULL REFERENCES secret_santa_events (id) ON DELETE CASCADE,
    gifter_id   INTEGER NOT NULL REFERENCES users (id),
    receiver_id INTEGER NOT NULL REFERENCES users (id),
    PRIMARY KEY (event_id, gifter_id)
);

CREATE TABLE wishlists
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   INTEGER     NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE wishlist_items
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wishlist_id INTEGER     NOT NULL REFERENCES wishlists (id) ON DELETE CASCADE,
    name        TEXT        NOT NULL,
    description TEXT,
    link        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_secret_santa_events_owner_id
    ON secret_santa_events (owner_id);

CREATE INDEX idx_event_participants_user_id
    ON event_participants (user_id);

CREATE INDEX idx_santa_assignments_receiver_id
    ON santa_assignments (receiver_id);

CREATE INDEX idx_wishlists_owner_id
    ON wishlists (owner_id);

CREATE INDEX idx_wishlist_items_wishlist_id
    ON wishlist_items (wishlist_id);